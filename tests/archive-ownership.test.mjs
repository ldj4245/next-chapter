import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile, readdir } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';
import { prepareStorage } from './storage-fixture.mjs';

test('보관본은 소유자만 조회하고 서버만 생성·접수하며, 재시도와 계정 삭제를 분리한다', async () => {
  const db = new PGlite();
  try {
    await db.exec("create role anon;create role authenticated;create role service_role bypassrls;create schema auth;create table auth.users(id uuid primary key,email text,created_at timestamptz default now(),last_sign_in_at timestamptz,email_confirmed_at timestamptz default now(),banned_until timestamptz,deleted_at timestamptz,encrypted_password text default 'never-return',raw_user_meta_data jsonb default '{}');create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;grant usage on schema auth to authenticated;");
    await prepareStorage(db);
    const folder = new URL('../supabase/migrations/', import.meta.url);
    for (const name of (await readdir(folder)).filter(n => n.endsWith('.sql') && n < '202610310002_record_archives.sql').sort()) await db.exec(await readFile(new URL(name, folder), 'utf8'));
    const alice = randomUUID(), bob = randomUUID(), existing = randomUUID();
    await db.query("insert into auth.users(id,email) values($1,'alice@example.com'),($2,'bob@example.com')", [alice, bob]);
    await db.query("insert into works(id,user_id,title,kind) values($1,$2,'변경하면 안 되는 기록','book')", [existing, bob]);
    const before = (await db.query('select to_jsonb(w) as row from works w')).rows;
    await db.exec(await readFile(new URL('202610310002_record_archives.sql', folder), 'utf8'));
    assert.deepEqual((await db.query('select to_jsonb(w) as row from works w')).rows, before);
    const rpc = async (name, args) => (await db.query('select to_jsonb(public.' + name + '(' + args.map((_, i) => '$' + (i + 1)).join(',') + ')) as row', args)).rows[0].row;
    const as = async (role, owner = '') => { await db.exec('reset role;set role ' + role); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [owner]); };
    const reserve = (owner, id = randomUUID(), digest = 'd'.repeat(64), dataId = 'A'.repeat(43)) => rpc('reserve_record_archive', [owner, id, '2026-10-01', '2026-10-31', ['days'], JSON.stringify({ days: 1 }), JSON.stringify({ ciphertext: 'encrypted-no-key' }), 100, digest, dataId, 'x'.repeat(200)]);
    const id = randomUUID();
    await as('authenticated', alice);
    await assert.rejects(reserve(alice, id));
    await assert.rejects(rpc('claim_record_archive', [alice, id]));
    await as('service_role');
    const created = await reserve(alice, id);
    assert.equal(created.state, 'prepared');
    const retry = await reserve(alice, id, 'd'.repeat(64), 'B'.repeat(43));
    assert.equal(retry.data_id, created.data_id, 'A retry keeps the originally signed item, including after two concurrent preparations');
    await assert.rejects(reserve(alice, id, 'e'.repeat(64)), /ARCHIVE_CONFLICT/);
    await assert.rejects(reserve(bob, id), /ARCHIVE_CONFLICT/);
    await as('authenticated', bob);
    assert.deepEqual((await db.query('select id,envelope from record_archives')).rows, []);
    await assert.rejects(db.query("update record_archives set state='confirmed' where id=$1", [id]));
    await assert.rejects(db.query('select signed_item from record_archives'));
    await as('authenticated', alice);
    assert.equal((await db.query('select id,envelope,receipt from record_archives')).rows.length, 1);
    await assert.rejects(db.query('delete from record_archives where id=$1', [id]));
    await assert.rejects(db.query('select signed_item from record_archives'));
    await as('anon'); await assert.rejects(db.query('select id from record_archives'));
    await as('service_role');
    await assert.rejects(rpc('claim_record_archive', [bob, id]), /ARCHIVE_NOT_FOUND/);
    const claimed = await rpc('claim_record_archive', [alice, id]);
    assert.equal(claimed.attempts, 1);
    await assert.rejects(rpc('claim_record_archive', [alice, id]), /ARCHIVE_BUSY/);
    await db.query("update record_archives set lease_until=now()-interval '1 second' where id=$1", [id]);
    assert.equal((await rpc('claim_record_archive', [alice, id])).attempts, 2);
    await db.query("update record_archives set state='submitted',submitted_at=now(),receipt='{}',lease_until=null where id=$1", [id]);
    assert.equal((await rpc('claim_record_archive', [alice, id])).attempts, 2, 'An accepted item is never uploaded again');
    await reserve(alice, randomUUID(), 'a'.repeat(64), 'C'.repeat(43));
    await reserve(alice, randomUUID(), 'b'.repeat(64), 'D'.repeat(43));
    await assert.rejects(reserve(alice, randomUUID(), 'c'.repeat(64), 'E'.repeat(43)), /ARCHIVE_DAILY_LIMIT/);
    const bobRecord = await reserve(bob, randomUUID(), 'f'.repeat(64), 'F'.repeat(43));
    await db.exec('reset role');
    await db.query('delete from auth.users where id=$1', [alice]);
    assert.equal((await db.query('select id from record_archives where user_id=$1', [alice])).rows.length, 0);
    assert.equal((await db.query('select id from record_archives where user_id=$1', [bob])).rows[0].id, bobRecord.id);
    assert.deepEqual((await db.query('select to_jsonb(w) as row from works w')).rows, before, 'Another member’s records are unchanged');
    await as('authenticated', bob);
    await db.exec("insert into account_deletion_requests(user_id) values(auth.uid())").catch(() => {});
    await db.exec('reset role'); await db.query('insert into account_deletion_requests(user_id) values($1)', [bob]);
    await as('service_role');
    await assert.rejects(rpc('claim_record_archive', [bob, bobRecord.id]), /ARCHIVE_ACCOUNT_UNAVAILABLE/);
  } finally { await db.close(); }
});

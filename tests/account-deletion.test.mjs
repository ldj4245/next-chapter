import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile, readdir } from 'node:fs/promises';
import { createHash, randomUUID } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';
import { prepareStorage } from './storage-fixture.mjs';

test('계정 탈퇴는 기존 기록 보존, 업로드 종료, 본인 사진 정리와 상대 기록 분리를 보장', async () => {
  const db = new PGlite();
  const alice = randomUUID(), bob = randomUUID(), cara = randomUUID();
  const task = randomUUID(), peerTask = randomUUID(), pendingId = randomUUID(), readyId = randomUUID();
  const tables = ['works', 'notes', 'reading_preferences', 'reading_sessions', 'planner_goals', 'daily_tasks', 'daily_reviews', 'task_photos', 'task_photo_deletions'];
  const asUser = async id => { await db.exec('reset role; set role authenticated;'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); };
  const rpc = async (name, values = []) => (await db.query('select ' + name + '(' + values.map((_, index) => '$' + (index + 1)).join(',') + ') as result', values)).rows[0].result;
  const ownerSnapshot = async owner => {
    await db.exec('reset role;');
    const result = {};
    for (const table of tables) result[table] = (await db.query('select to_jsonb(t) as row from public.' + table + ' t where user_id=$1 order by to_jsonb(t)::text', [owner])).rows;
    return result;
  };
  const storageObject = async (path, size = 250) => db.query("insert into storage.objects(bucket_id,name,metadata) values('task-photos',$1,jsonb_build_object('size',$2::integer,'mimetype','image/webp'))", [path, size]);
  const busy = error => error.code === 'P0001' && error.message === 'ACCOUNT_PHOTO_BUSY';
  const deleting = error => error.code === 'P0001' && error.message === 'ACCOUNT_DELETING';
  try {
    await db.exec("create role anon; create role authenticated; create role supabase_auth_admin; create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$; grant usage on schema auth to authenticated,supabase_auth_admin; grant select,delete on auth.users to supabase_auth_admin;");
    await prepareStorage(db);
    const folder = new URL('../supabase/migrations/', import.meta.url);
    for (const name of (await readdir(folder)).filter(name => name.endsWith('.sql') && name < '202610230001_account.sql').sort()) await db.exec(await readFile(new URL(name, folder), 'utf8'));
    await db.query('insert into auth.users values($1),($2),($3)', [alice, bob, cara]);
    for (const [owner, id] of [[alice, task], [bob, peerTask]]) {
      await asUser(owner);
      const work = randomUUID(), note = randomUUID(), goal = randomUUID();
      await db.query("insert into works(id,user_id,title,kind) values($1,$2,'나만의 책','book')", [work, owner]);
      await db.query("insert into notes(id,user_id,work_id,content,thought) values($1,$2,$3,'보존할 인용','보존할 생각')", [note, owner, work]);
      await db.query("insert into planner_goals(id,user_id,title,period) values($1,$2,'나의 목표','short')", [goal, owner]);
      await db.query("insert into daily_tasks(id,user_id,day,title,note,work_id,goal_id) values($1,$2,'2026-10-23','오늘의 할 일','개인 메모',$3,$4)", [id, owner, work, goal]);
      await db.query("insert into daily_reviews(user_id,day,helped) values($1,'2026-10-23','개인 회고')", [owner]);
      await db.query('insert into reading_preferences(user_id,work_id) values($1,$2)', [owner, work]);
      await db.query("insert into reading_sessions(user_id,work_id,work_title,task_id,goal_id,note_id,memo) values($1,$2,'나만의 책',$3,$4,$5,'개인 집중 메모')", [owner, work, id, goal, note]);
      await db.query("insert into partner_profiles(user_id,nickname) values($1,'내 이름')", [owner]);
    }
    await asUser(alice);
    const pending = await rpc('reserve_task_photo', [task, pendingId]);
    const ready = await rpc('reserve_task_photo', [task, readyId]);
    await db.exec('reset role;');
    await storageObject(ready.original_path, 1000); await storageObject(ready.thumbnail_path, 200);
    await asUser(alice); await rpc('finalize_task_photo', [readyId, 500, 400, 1000, 200]);
    const beforeAlice = await ownerSnapshot(alice), beforeBob = await ownerSnapshot(bob);
    await db.exec(await readFile(new URL('202610230001_account.sql', folder), 'utf8'));
    assert.deepEqual(await ownerSnapshot(alice), beforeAlice, 'The migration never rewrites existing private records or photo metadata');
    assert.deepEqual(await ownerSnapshot(bob), beforeBob);
    assert.equal((await db.query('select count(*)::integer as count from account_photo_uploads where photo_id=$1 and user_id=$2', [pendingId, alice])).rows[0].count, 1, 'An existing pending upload receives a deletion-blocking lease');
    await asUser(alice);
    await assert.rejects(rpc('own_account_photo_paths'));
    await assert.rejects(rpc('own_account_has_photo_objects'));
    await assert.rejects(db.query('select * from account_photo_uploads'), 'Lease metadata has no client read grant');
    await assert.rejects(db.query('insert into account_deletion_requests(user_id) values($1)', [alice]));
    await assert.rejects(rpc('reserve_task_photo_before_account', [task, randomUUID()]), 'The unguarded reservation cannot be invoked directly');
    await assert.rejects(rpc('finalize_task_photo_before_account', [readyId, 500, 400, 1000, 200]));
    assert.equal((await rpc('reserve_task_photo', [task, readyId])).state, 'ready');
    await db.exec('reset role;');
    assert.equal((await db.query('select count(*)::integer as count from account_photo_uploads where photo_id=$1', [readyId])).rows[0].count, 0, 'An immutable ready retry never creates an upload lease');
    await asUser(alice);
    const token = 'd'.repeat(64);
    await rpc('create_partner_invite', [createHash('sha256').update(token).digest('hex')]);
    await asUser(bob); const pair = await rpc('accept_partner_invite', [token]);
    await db.query('update daily_tasks set shared=true where id=$1', [peerTask]);
    await asUser(alice); await db.query('update daily_tasks set shared=true,photos_shared=true where id=$1', [task]);
    await assert.rejects(rpc('prepare_own_account_deletion'), busy, 'An active upload blocks deletion before the marker or partner revocation');
    assert.equal((await db.query('select * from account_deletion_requests')).rows.length, 0);
    assert.equal((await rpc('partner_state')).connection.id, pair.id);
    // A task/photo FK cascade can remove a reservation while its HTTP upload
    // still transfers bytes. Its independent lease must continue blocking.
    const transientTask = randomUUID(), transientPhoto = randomUUID();
    await db.query("insert into daily_tasks(id,user_id,day,title) values($1,$2,'2026-10-23','삭제 중 업로드')", [transientTask, alice]);
    await rpc('reserve_task_photo', [transientTask, transientPhoto]);
    await db.query('delete from daily_tasks where id=$1', [transientTask]);
    await db.query('delete from task_photos where id=$1', [pendingId]);
    await assert.rejects(rpc('prepare_own_account_deletion'), busy, 'Deleting reservations does not conceal an in-flight server transfer');
    await db.exec('reset role;');
    await db.query("update account_photo_uploads set created_at=now()-interval '11 minutes' where user_id=$1", [alice]);
    // Include an expired pending record as well as leases without photo rows.
    await asUser(alice); const expiredId = randomUUID(), expired = await rpc('reserve_task_photo', [task, expiredId]);
    await db.exec('reset role;');
    await db.query("update task_photos set created_at=now()-interval '11 minutes' where id=$1", [expiredId]);
    await db.query("update account_photo_uploads set created_at=now()-interval '11 minutes' where photo_id=$1", [expiredId]);
    const orphan = alice + '/' + randomUUID() + '/' + randomUUID() + '/image.webp';
    const peerPath = bob + '/' + randomUUID() + '/' + randomUUID() + '/image.webp';
    const deceptivePrefix = alice + '0/' + randomUUID() + '/image.webp';
    await storageObject(orphan); await storageObject(peerPath); await storageObject(deceptivePrefix);
    await db.query("insert into task_photo_deletions(path,user_id) select $1::text||'/'||gen_random_uuid()::text||'/'||gen_random_uuid()::text||'/image.webp',$1::uuid from generate_series(1,1100)", [alice]);
    const bobPrivate = await ownerSnapshot(bob);
    await asUser(alice); assert.equal(await rpc('prepare_own_account_deletion'), true);
    assert.equal(await rpc('prepare_own_account_deletion'), true, 'A cleanup retry is idempotent');
    assert.equal((await rpc('partner_state')).connection, null);
    assert.equal((await db.query('select * from account_deletion_requests')).rows.length, 1);
    const paths = await rpc('own_account_photo_paths');
    assert.ok(paths.length > 1100, 'The JSON inventory includes more than the usual REST 1000-row limit');
    for (const expected of [ready.original_path, ready.thumbnail_path, pending.original_path, pending.thumbnail_path, expired.original_path, expired.thumbnail_path, orphan]) assert.ok(paths.includes(expected));
    assert.equal(paths.length, new Set(paths).size, 'Live storage, metadata and outbox inventory is deduplicated');
    assert.ok(paths.every(path => path.startsWith(alice + '/')));
    assert.ok(!paths.includes(peerPath) && !paths.includes(deceptivePrefix));
    assert.equal(await rpc('own_account_has_photo_objects'), true);
    await assert.rejects(rpc('reserve_task_photo', [task, randomUUID()]), deleting);
    await assert.rejects(rpc('reserve_task_photo', [task, readyId]), deleting);
    await assert.rejects(rpc('finalize_task_photo', [readyId, 500, 400, 1000, 200]), deleting);
    await asUser(bob);
    assert.equal((await db.query('select * from account_deletion_requests')).rows.length, 0);
    await assert.rejects(rpc('own_account_photo_paths'));
    await assert.rejects(rpc('own_account_has_photo_objects'));
    assert.equal((await rpc('partner_state')).connection, null);
    await db.exec('reset role; set role anon;');
    for (const name of ['prepare_own_account_deletion', 'own_account_photo_paths', 'own_account_has_photo_objects']) await assert.rejects(rpc(name));
    // Storage bytes are removed through the actual Storage API in HTTP tests;
    // here only its isolated test fixture metadata is updated to model success.
    await db.exec('reset role;');
    for (const path of paths) await db.query("delete from storage.objects where bucket_id='task-photos' and name=$1", [path]);
    await asUser(alice); assert.equal(await rpc('own_account_has_photo_objects'), false, 'Stale metadata/outbox entries do not masquerade as actual remaining objects');
    assert.ok((await rpc('own_account_photo_paths')).length > 0);
    await db.exec('reset role; set role supabase_auth_admin;');
    await db.query('delete from auth.users where id=$1', [alice]);
    await db.exec('reset role;');
    for (const table of [...tables.filter(name => name !== 'task_photo_deletions'), 'account_deletion_requests', 'account_photo_uploads', 'partner_profiles', 'partner_members', 'partner_invites']) assert.equal((await db.query('select count(*)::integer as count from public.' + table + ' where user_id=$1', [alice])).rows[0].count, 0, 'Auth cascade clears ' + table);
    assert.equal((await db.query('select count(*)::integer as count from storage.objects where name=$1', [peerPath])).rows[0].count, 1, 'Another owner’s files survive');
    assert.equal((await db.query('select count(*)::integer as count from partner_connections where id=$1', [pair.id])).rows[0].count, 0);
    const afterBob = await ownerSnapshot(bob);
    for (const table of tables.filter(name => name !== 'daily_tasks')) assert.deepEqual(afterBob[table], bobPrivate[table], 'The counterpart’s private ' + table + ' survives');
    const privateTask = row => Object.fromEntries(Object.entries(row).filter(([key]) => !['shared', 'shared_connection_id', 'photos_shared', 'photo_connection_id', 'updated_at'].includes(key)));
    assert.deepEqual(afterBob.daily_tasks.map(({ row }) => privateTask(row)), bobPrivate.daily_tasks.map(({ row }) => privateTask(row)), 'Only the old sharing selection changes on the counterpart’s task');
    await asUser(bob); assert.equal((await db.query('select * from task_photo_deletions')).rows.length, 0, 'The retained cleanup outbox never exposes another person’s paths');
    await asUser(alice); await assert.rejects(rpc('prepare_own_account_deletion'), 'An old JWT cannot create a marker after Auth deletion');
  } finally { await db.close(); }
});

import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';
import { prepareStorage } from './storage-fixture.mjs';

test('사진은 소유자별 3장 원자적 예약, 개별 공유 선택, 연결 해제 즉시 회수와 삭제 outbox를 보장', async () => {
  const db = new PGlite();
  const alice = '11111111-1111-4111-8111-111111111111', bob = '22222222-2222-4222-8222-222222222222', cara = '33333333-3333-4333-8333-333333333333';
  const task = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', other = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
  const ids = ['11111111-aaaa-4aaa-8aaa-111111111111', '22222222-aaaa-4aaa-8aaa-222222222222', '33333333-aaaa-4aaa-8aaa-333333333333', '44444444-aaaa-4aaa-8aaa-444444444444'];
  const asUser = async user => { await db.exec('reset role; set role authenticated;'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [user]); };
  const rpc = async (name, values = []) => (await db.query('select ' + name + '(' + values.map((_, index) => '$' + (index + 1)).join(',') + ') as result', values)).rows[0].result;
  const token = 'a'.repeat(64);
  try {
    await db.exec("create role anon; create role authenticated; create role supabase_auth_admin; create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$; grant usage on schema auth to authenticated,supabase_auth_admin; grant select,delete on auth.users to supabase_auth_admin;");
    await prepareStorage(db);
    const folder = new URL('../supabase/migrations/', import.meta.url);
    for (const name of (await readdir(folder)).filter(name => name.endsWith('.sql')).sort()) await db.exec(await readFile(new URL(name, folder), 'utf8'));
    await db.query('insert into auth.users values($1),($2),($3)', [alice, bob, cara]);
    await asUser(alice);
    await db.query("insert into partner_profiles(user_id,nickname) values($1,'나의 이름')", [alice]);
    await db.query("insert into daily_tasks(id,user_id,day,title,note) values($1,$2,(now() at time zone 'Asia/Seoul')::date,'사진을 남길 활동','나만 보는 메모')", [task, alice]);
    const before = (await db.query('select * from daily_tasks where id=$1', [task])).rows[0];
    assert.equal(before.photos_shared, false); assert.equal(before.photo_connection_id, null);
    await assert.rejects(db.query("insert into task_photos(id,user_id,task_id,original_path,thumbnail_path) values($1,$2,$3,'bad','bad')", [ids[0], alice, task]));
    const first = await rpc('reserve_task_photo', [task, ids[0]]);
    assert.equal(first.state, 'pending'); assert.equal(first.original_path, alice + '/' + task + '/' + ids[0] + '/image.webp');
    assert.equal(await rpc('can_read_task_photo', [ids[0]]), false);
    await assert.rejects(rpc('reserve_task_photo', [task, ids[0]]), 'Concurrent same-ID upload never overwrites another writer');
    await assert.rejects(rpc('finalize_task_photo', [ids[0], 800, 600, 1200, 300]), 'No ready record without both actual storage objects');
    await assert.rejects(db.query("insert into storage.objects(bucket_id,name,metadata) values('task-photos',$1,'{}')", [first.original_path]), 'Owners cannot bypass Sharp via direct storage upload');
    await db.exec('reset role;');
    for (const [path, size] of [[first.original_path, 1200], [first.thumbnail_path, 300]]) {
      await db.query("insert into storage.objects(bucket_id,name,metadata) values('task-photos',$1,jsonb_build_object('size',$2::integer,'mimetype','image/webp'))", [path, size]);
    }
    await asUser(alice);
    const ready = await rpc('finalize_task_photo', [ids[0], 800, 600, 1200, 300]);
    assert.equal(ready.state, 'ready'); assert.equal(ready.width, 800);
    assert.equal((await rpc('reserve_task_photo', [task, ids[0]])).id, ids[0], 'Lost ready response retries idempotently');
    assert.equal((await db.query("update storage.objects set metadata='{}' where name=$1 returning id", [first.original_path])).rows.length, 0, 'Ready photo bytes are immutable');
    assert.equal(await rpc('can_read_task_photo', [ids[0]]), true);
    await rpc('reserve_task_photo', [task, ids[1]]); await rpc('reserve_task_photo', [task, ids[2]]);
    await assert.rejects(rpc('reserve_task_photo', [task, ids[3]]), 'Pending rows count toward the atomic limit');
    assert.equal((await db.query('select count(*)::integer as count from task_photos')).rows[0].count, 3);
    assert.deepEqual((await db.query('select * from daily_tasks where id=$1', [task])).rows[0], before, 'Upload metadata does not modify private task state');
    await rpc('create_partner_invite', [createHash('sha256').update(token).digest('hex')]);
    await asUser(bob);
    await db.query("insert into partner_profiles(user_id,nickname) values($1,'상대 이름')", [bob]);
    const pair = await rpc('accept_partner_invite', [token]);
    await assert.rejects(rpc('reserve_task_photo', [task, ids[3]]));
    assert.equal((await db.query('select * from task_photos')).rows.length, 0);
    assert.equal((await db.query('select * from storage.objects')).rows.length, 0);
    assert.equal(await rpc('can_read_task_photo', [ids[0]]), false);
    await asUser(alice);
    await db.query('update daily_tasks set shared=true where id=$1', [task]);
    await asUser(bob);
    const day = (await db.query("select (now() at time zone 'Asia/Seoul')::date::text as day")).rows[0].day;
    assert.deepEqual((await rpc('partner_day', [day])).activities[0].photos, [], 'Sharing a task alone does not share its photos');
    assert.equal(await rpc('can_read_task_photo', [ids[0]]), false);
    await asUser(alice);
    await assert.rejects(db.query('update daily_tasks set photos_shared=true,photo_connection_id=$1 where id=$2', [other, task]));
    await db.query('update daily_tasks set photos_shared=true where id=$1', [task]);
    assert.equal((await db.query('select photo_connection_id from daily_tasks where id=$1', [task])).rows[0].photo_connection_id, pair.id);
    await asUser(bob);
    const photo = (await rpc('partner_day', [day])).activities[0].photos[0];
    assert.deepEqual(Object.keys(photo).sort(), ['bytes', 'created_at', 'height', 'id', 'task_id', 'thumbnail_url', 'url', 'width']);
    assert.equal(photo.id, ids[0]); assert.equal(photo.url, '/api/photos/' + ids[0] + '/image?size=full');
    assert.equal(await rpc('can_read_task_photo', [ids[0]]), true);
    assert.equal((await db.query('select * from storage.objects')).rows.length, 0, 'A partner cannot mint Storage signed URLs');
    assert.equal((await db.query('delete from task_photos where id=$1 returning id', [ids[0]])).rows.length, 0);
    await asUser(cara); assert.equal(await rpc('can_read_task_photo', [ids[0]]), false);
    await asUser(alice);
    await rpc('revoke_partner', [pair.id]);
    const cleared = (await db.query('select shared,photos_shared,photo_connection_id from daily_tasks where id=$1', [task])).rows[0];
    assert.deepEqual(cleared, { shared: false, photos_shared: false, photo_connection_id: null });
    await asUser(bob); assert.equal(await rpc('can_read_task_photo', [ids[0]]), false);
    await asUser(alice);
    await db.query('delete from task_photos where id=$1', [ids[1]]);
    assert.equal((await db.query('select count(*)::integer as count from task_photo_deletions')).rows[0].count, 2);
    await rpc('reserve_task_photo', [task, ids[3]]);
    // Publishing another successfully normalized upload resets photo sharing
    // exactly once; an already-ready request replay preserves a later choice.
    const pending = (await db.query('select * from task_photos where id=$1', [ids[2]])).rows[0];
    await db.exec('reset role;');
    for (const [path, size] of [[pending.original_path, 1000], [pending.thumbnail_path, 200]]) await db.query("insert into storage.objects(bucket_id,name,metadata) values('task-photos',$1,jsonb_build_object('size',$2::integer,'mimetype','image/webp'))", [path, size]);
    await asUser(alice);
    // Reconnect the same participants with a new pair; nothing is inherited.
    await rpc('create_partner_invite', [createHash('sha256').update(token).digest('hex')]);
    await asUser(bob); const nextPair = await rpc('accept_partner_invite', [token]);
    assert.notEqual(nextPair.id, pair.id);
    assert.equal(await rpc('can_read_task_photo', [ids[0]]), false);
    await asUser(alice);
    await db.query('update daily_tasks set shared=true,photos_shared=true where id=$1', [task]);
    await rpc('finalize_task_photo', [ids[2], 700, 500, 1000, 200]);
    assert.equal((await db.query('select photos_shared from daily_tasks where id=$1', [task])).rows[0].photos_shared, false);
    await db.query('update daily_tasks set photos_shared=true where id=$1', [task]);
    await rpc('finalize_task_photo', [ids[2], 700, 500, 1000, 200]);
    assert.equal((await db.query('select photos_shared from daily_tasks where id=$1', [task])).rows[0].photos_shared, true);
    await db.query('delete from daily_tasks where id=$1', [task]);
    assert.equal((await db.query('select * from task_photos')).rows.length, 0);
    assert.equal((await db.query('select * from storage.objects')).rows.length, 0, 'Orphan bytes cannot be read even by the owner until deleted');
    assert.equal((await db.query('select count(*)::integer as count from task_photo_deletions')).rows[0].count, 8);
    await db.query('delete from storage.objects where name=$1', [first.original_path]);
    await db.query('delete from storage.objects where name=$1', [first.thumbnail_path]);
    await db.query("insert into daily_tasks(id,user_id,day,title) values($1,$2,'2026-10-14','계정 정리')", [other, alice]);
    await rpc('reserve_task_photo', [other, ids[0]]);
    await db.exec('reset role; set role supabase_auth_admin;');
    await db.query('delete from auth.users where id=$1', [alice]);
    await asUser(bob); assert.equal((await db.query('select * from task_photo_deletions')).rows.length, 0, 'Cleanup queue is private and never blocks account deletion');
  } finally { await db.close(); }
});

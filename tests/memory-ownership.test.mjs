import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile, readdir } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { randomUUID } from 'node:crypto';
import { prepareStorage } from './storage-fixture.mjs';

test('메모 원자적 정리·revision·비공개 소유권과 옛 기록 snapshot 보존', async () => {
  const db = new PGlite();
  try {
    await db.exec("create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$; grant usage on schema auth to authenticated;");
    await prepareStorage(db);
    const migrations = new URL('../supabase/migrations/', import.meta.url);
    for (const name of (await readdir(migrations)).filter(name => name.endsWith('.sql')).sort()) await db.exec(await readFile(new URL(name, migrations), 'utf8'));
    const alice = '11111111-1111-4111-8111-111111111111', bob = '22222222-2222-4222-8222-222222222222';
    const memoId = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', book = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
    const reviewMemo = 'cccccccc-cccc-4ccc-8ccc-cccccccccccc', noteMemo = 'dddddddd-dddd-4ddd-8ddd-dddddddddddd';
    const invalidMemo = 'eeeeeeee-eeee-4eee-8eee-eeeeeeeeeeee', revisitId = 'ffffffff-ffff-4fff-8fff-ffffffffffff';
    const oldNote = '99999999-9999-4999-8999-999999999999', revisitNote = '88888888-8888-4888-8888-888888888888';
    const asUser = async user => { await db.exec('reset role; set role authenticated;'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [user]); };
    const create = async (id, content) => (await db.query('select * from create_quick_memo($1,$2)', [id, content])).rows[0];
    const convert = async (id, kind = 'task', day = '2026-10-10', workId = null, revision = 1) => (await db.query('select * from convert_quick_memo($1,$2,$3,$4,$5)', [id, kind, day, workId, revision])).rows[0];
    await db.query('insert into auth.users values($1),($2)', [alice, bob]);
    await asUser(alice);
    const content = '  첫 줄\n\n마지막 줄  ';
    await create(memoId, content);
    assert.equal((await create(memoId, content)).revision, 1);
    await assert.rejects(create(memoId, '바뀐 요청'), error => error.code === 'P0001' && error.message === 'MEMO_ID_CONTENT_CONFLICT');
    await assert.rejects(db.query('insert into quick_memos(id,user_id,content) values($1,$2,$3)', [invalidMemo, alice, '직접 쓰기']));
    await assert.rejects(db.query('update quick_memos set converted_kind=$1', ['task']));
    await assert.rejects(create(invalidMemo, ' \n\t '));
    await assert.rejects(create(invalidMemo, 'x'.repeat(2001)));
    await assert.rejects(db.query('select * from update_quick_memo($1,$2,2)', [memoId, '고침']), error => error.code === 'P0001' && error.message === 'MEMO_REVISION_CONFLICT');
    const edited = (await db.query('select * from update_quick_memo($1,$2,1)', [memoId, content + '\n추가'])).rows[0];
    assert.equal(edited.revision, 2);
    await assert.rejects(convert(memoId), error => error.code === 'P0001' && error.message === 'MEMO_REVISION_CONFLICT');
    const taskMemo = await convert(memoId, 'task', '2026-10-10', null, 2);
    assert.equal(taskMemo.content, content + '\n추가'); assert.equal(taskMemo.converted_kind, 'task');
    const task = (await db.query('select * from daily_tasks where id=$1', [taskMemo.converted_id])).rows[0];
    assert.equal(task.title, '첫 줄'); assert.equal(task.note, content + '\n추가');
    assert.equal((await convert(memoId, 'review', '2026-10-11', null, 1)).converted_id, task.id, 'stale retry returns same target');
    assert.equal((await db.query('select * from daily_tasks')).rows.length, 1);
    await assert.rejects(db.query('select * from update_quick_memo($1,$2,3)', [memoId, '정리 후 수정']), error => error.code === '55000');
    await db.query('delete from quick_memos where id=$1', [memoId]);
    assert.equal((await db.query('select id from daily_tasks where id=$1', [task.id])).rows.length, 1);

    await create(reviewMemo, '  회고에 더한 생각\n끝  ');
    await db.query("insert into daily_reviews(user_id,day,helped,gained) values($1,'2026-10-01','기존 답변','배운 것')", [alice]);
    await convert(reviewMemo, 'review', '2026-10-01');
    const review = (await db.query("select * from daily_reviews where day='2026-10-01'")).rows[0];
    assert.equal(review.helped, '기존 답변'); assert.equal(review.gained, '배운 것'); assert.equal(review.revision, 2);
    assert.deepEqual(review.document.blocks.map(b => b.text), ['잘 된 것', '기존 답변', '얻은 것', '배운 것', '  회고에 더한 생각\n끝  ']);
    await assert.rejects(db.query("select save_daily_review('2026-10-01',1,'stale','','','',null)"), error => error.message.includes('REVIEW_CONFLICT'));
    assert.deepEqual((await db.query("select document from daily_reviews where day='2026-10-01'")).rows[0].document, review.document);
    const saved = (await db.query("select save_daily_review('2026-10-01',2,'기존 답변','','배운 것','',$1) as review", [JSON.stringify(review.document)])).rows[0].review;
    assert.equal(saved.revision, 3);
    await assert.rejects(db.query("select save_daily_review('2026-10-01',0,'','','','',null)"));
    assert.equal((await db.query("select save_daily_review('2026-10-02',0,'새 기록','','','',null) as review")).rows[0].review.revision, 1);
    await create(invalidMemo, '추가 공간이 없다');
    const fullDoc = { version: 1, blocks: [{ id: invalidMemo, kind: 'paragraph', text: '가'.repeat(24000), checked: false }] };
    await db.query("insert into daily_reviews(user_id,day,document) values($1,'2026-10-03',$2)", [alice, JSON.stringify(fullDoc)]);
    await assert.rejects(convert(invalidMemo, 'review', '2026-10-03'), error => error.code === '22001');
    assert.equal((await db.query('select converted_kind from quick_memos where id=$1', [invalidMemo])).rows[0].converted_kind, null);
    assert.deepEqual((await db.query("select document from daily_reviews where day='2026-10-03'")).rows[0].document, fullDoc);
    const blockLimit = { version: 1, blocks: Array.from({ length: 200 }, () => ({ id: randomUUID(), kind: 'paragraph', text: '', checked: false })) };
    await db.query("insert into daily_reviews(user_id,day,document) values($1,'2026-10-04',$2)", [alice, JSON.stringify(blockLimit)]);
    await assert.rejects(convert(invalidMemo, 'review', '2026-10-04'), error => error.code === '22001');
    assert.equal((await db.query('select revision from quick_memos where id=$1', [invalidMemo])).rows[0].revision, 1);
    await convert(invalidMemo, 'review', '2026-10-01');
    const appended = (await db.query("select * from daily_reviews where day='2026-10-01'")).rows[0];
    assert.equal(appended.revision, 4);
    assert.deepEqual(appended.document.blocks.slice(0, -1), review.document.blocks, 'append keeps the latest saved document');
    assert.equal(appended.document.blocks.at(-1).text, '추가 공간이 없다');
    await assert.rejects(db.query("select save_daily_review('2026-10-01',3,'','','','',$1)", [JSON.stringify(review.document)]), error => error.message.includes('REVIEW_CONFLICT'));

    await db.query("insert into works(id,user_id,title,kind) values($1,$2,'내 책','book')", [book, alice]);
    await create(noteMemo, '  작품에 남길 말\n둘째 줄  ');
    await convert(noteMemo, 'note', '2026-10-01', book);
    const convertedNote = (await db.query('select * from notes')).rows[0];
    assert.equal(convertedNote.content, '  작품에 남길 말\n둘째 줄  '); assert.equal(convertedNote.thought, '');
    await db.query("insert into notes(id,user_id,work_id,content,thought,created_at) values($1,$2,$3,'  예전 문장  ','옛 생각',now()-interval '20 days')", [oldNote, alice, book]);
    const sources = [];
    for (let i = 0; i < 10; i++) { const source = (await db.query('select next_memory_source($1) as item', [i])).rows[0].item; if (!source) break; sources.push(source); }
    assert.ok(sources.some(s => s.source_id === oldNote));
    assert.ok(!sources.some(s => s.source_id === convertedNote.id), 'recent notes excluded');
    assert.deepEqual((await db.query('select next_memory_source(0) as item')).rows[0].item, sources[0], 'deterministic pagination');
    const entry = (await db.query("select * from create_record_revisit($1,'review',null,'2026-10-01','  지금 생각  ')", [revisitId])).rows[0];
    assert.ok(entry.source_text.includes('  회고에 더한 생각\n끝  ')); assert.equal(entry.thought, '  지금 생각  ');
    assert.equal((await db.query("select * from create_record_revisit($1,'review',null,'2026-10-01','  지금 생각  ')", [revisitId])).rows[0].id, revisitId);
    await assert.rejects(db.query("select * from create_record_revisit($1,'review',null,'2026-10-01','다른 생각')", [revisitId]), error => error.code === 'P0001' && error.message === 'REVISIT_ID_CONTENT_CONFLICT');
    const noteEntry = (await db.query("select * from create_record_revisit($1,'note',$2,null,'지금은 달라졌다')", [revisitNote, oldNote])).rows[0];
    assert.equal(noteEntry.source_text, '  예전 문장  \n\n옛 생각'); assert.equal(noteEntry.source_work_id, book);
    await db.query('delete from notes where id=$1', [convertedNote.id]);
    assert.equal((await convert(noteMemo, 'note', '2026-10-01', book)).converted_id, convertedNote.id, 'deleted destination is never recreated on retry');
    assert.equal((await db.query('select id from notes where id=$1', [convertedNote.id])).rows.length, 0);
    await assert.rejects(db.query("insert into record_revisits(id,user_id,source_kind,source_day,source_date,source_title,source_text,thought) values(gen_random_uuid(),$1,'review','2026-10-01','2026-10-01','위조','타인의 문장','생각')", [alice]));
    await asUser(bob);
    for (const table of ['quick_memos', 'record_revisits']) {
      assert.equal((await db.query('select * from ' + table)).rows.length, 0);
      assert.equal((await db.query('delete from ' + table + ' where user_id=$1 returning id', [alice])).rows.length, 0);
    }
    assert.equal((await db.query('select next_memory_source(0) as item')).rows[0].item, null);
    await assert.rejects(convert(reviewMemo, 'task'));
    await assert.rejects(db.query('select * from update_quick_memo($1,$2,2)', [reviewMemo, '타인 수정']));
    await assert.rejects(db.query("select * from create_record_revisit(gen_random_uuid(),'note',$1,null,'남의 문장')", [oldNote]));
    await create(memoId, '남의 작품 연결');
    await assert.rejects(convert(memoId, 'note', '2026-10-01', book));
    assert.equal((await db.query('select converted_kind from quick_memos where id=$1', [memoId])).rows[0].converted_kind, null);
    await asUser(alice);
    await db.query("delete from daily_reviews where day='2026-10-01'");
    await db.query('delete from notes where id=$1', [oldNote]);
    assert.equal((await db.query('select source_text from record_revisits where id=$1', [revisitId])).rows[0].source_text, entry.source_text);
    assert.equal((await db.query("select * from create_record_revisit($1,'review',null,'2026-10-01','  지금 생각  ')", [revisitId])).rows[0].id, revisitId, 'retry succeeds after source deletion');
    assert.equal((await db.query('select source_text from record_revisits where id=$1', [revisitNote])).rows[0].source_text, noteEntry.source_text);
    await db.exec('reset role; set role anon;');
    for (const table of ['quick_memos', 'record_revisits']) await assert.rejects(db.query('select * from ' + table));
    await assert.rejects(db.query('delete from quick_memos where id=$1', [reviewMemo]));
    await assert.rejects(db.query('delete from record_revisits where id=$1', [revisitId]));
    await assert.rejects(db.query('select * from create_quick_memo($1,$2)', [memoId, 'anon']));
    await assert.rejects(db.query('select * from update_quick_memo($1,$2,1)', [reviewMemo, 'anon']));
    await assert.rejects(convert(reviewMemo));
    await assert.rejects(db.query("select * from create_record_revisit($1,'review',null,'2026-10-01','anon')", [revisitId]));
    await assert.rejects(db.query('select next_memory_source(0)'));
    await assert.rejects(db.query("select save_daily_review('2026-10-01',0,'','','','',null)"));
  } finally { await db.close(); }
});

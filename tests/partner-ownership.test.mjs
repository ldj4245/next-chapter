import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile, readdir } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { createHash } from 'node:crypto';

test('상대 연결은 한 명만 원자적으로 수락하고 선택한 하루 기록만 공개하며 해제 후 권한을 회수', async () => {
  const db = new PGlite();
  const alice = '11111111-1111-4111-8111-111111111111', bob = '22222222-2222-4222-8222-222222222222', cara = '33333333-3333-4333-8333-333333333333';
  const legacy = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', task = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb', hidden = 'cccccccc-cccc-4ccc-8ccc-cccccccccccc', partial = 'dddddddd-dddd-4ddd-8ddd-dddddddddddd';
  const h1 = '1'.repeat(64), h2 = '2'.repeat(64), h3 = '3'.repeat(64), h4 = '4'.repeat(64), h5 = '5'.repeat(64);
  const asUser = async user => { await db.exec('reset role; set role authenticated;'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [user]); };
  const tokenHash = token => createHash('sha256').update(token).digest('hex');
  const rpc = async (name, values = []) => (await db.query('select ' + name + '(' + values.map((_, i) => '$' + (i + 1)).join(',') + ') as result', name === 'create_partner_invite' ? [tokenHash(values[0])] : values)).rows[0].result;
  try {
    await db.exec("create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$; grant usage on schema auth to authenticated;");
    const folder = new URL('../supabase/migrations/', import.meta.url);
    for (const name of (await readdir(folder)).filter(name => name.endsWith('.sql') && name < '202610140001_partner.sql').sort()) await db.exec(await readFile(new URL(name, folder), 'utf8'));
    await db.query('insert into auth.users values($1),($2),($3)', [alice, bob, cara]);
    await asUser(alice);
    await db.query("insert into daily_tasks(id,user_id,day,title,status,note) values($1,$2,'2026-10-01','기존 완료 기록','completed','기존 비공개 메모')", [legacy, alice]);
    const before = (await db.query('select * from daily_tasks where id=$1', [legacy])).rows[0];
    await db.exec('reset role;');
    await db.exec(await readFile(new URL('202610140001_partner.sql', folder), 'utf8'));
    await db.exec(await readFile(new URL('202610140002_partner_token.sql', folder), 'utf8'));
    await db.exec(await readFile(new URL('202610140003_note_cascade.sql', folder), 'utf8'));
    await db.exec('create role supabase_auth_admin; grant usage on schema auth to supabase_auth_admin; grant select,delete on auth.users to supabase_auth_admin;');
    await asUser(alice);
    const after = (await db.query('select * from daily_tasks where id=$1', [legacy])).rows[0];
    for (const [key, value] of Object.entries(before)) assert.deepEqual(after[key], value, 'Migration preserves ' + key);
    assert.equal(after.shared, false); assert.equal(after.public_note, ''); assert.equal(after.shared_connection_id, null); assert.equal(after.completed_at, null);
    await assert.rejects(db.query('update daily_tasks set shared=true where id=$1', [legacy]));
    await assert.rejects(rpc('partner_day', ['2026-10-14']));
    await assert.rejects(rpc('create_partner_invite', [h1]));
    for (const nickname of ['가', 'x'.repeat(25), '<이름>', '줄\n바꿈']) await assert.rejects(db.query('insert into partner_profiles(user_id,nickname) values($1,$2)', [alice, nickname]));
    await db.query("insert into partner_profiles(user_id,nickname) values($1,'민수')", [alice]);
    const pending = await rpc('create_partner_invite', [h1]);
    assert.equal(Object.keys(pending).join(','), 'expires_at');
    assert.equal((await rpc('partner_state')).invite.expires_at, pending.expires_at);
    await assert.rejects(db.query('select token_hash from partner_invites'));
    await assert.rejects(db.query('insert into partner_members(user_id,connection_id) values($1,$2)', [alice, task]));
    await assert.rejects(rpc('accept_partner_invite', [h1]));
    await rpc('create_partner_invite', [h2]);
    await assert.rejects(rpc('preview_partner_invite', [h1]));
    await db.exec('reset role; set role anon;');
    assert.deepEqual(Object.keys(await rpc('preview_partner_invite', [h2])).sort(), ['expires_at', 'nickname']);
    assert.equal((await rpc('preview_partner_invite', [h2])).nickname, '민수');
    for (const table of ['partner_profiles', 'partner_connections', 'partner_members', 'partner_invites', 'daily_tasks', 'daily_reviews', 'reading_sessions']) await assert.rejects(db.query('select * from ' + table));
    await assert.rejects(rpc('partner_state')); await assert.rejects(rpc('accept_partner_invite', [h2]));
    await asUser(bob);
    assert.equal((await db.query('select * from partner_profiles')).rows.length, 0);
    await db.query("insert into partner_profiles(user_id,nickname) values($1,'지훈')", [bob]);
    await rpc('create_partner_invite', [h3]);
    await assert.rejects(rpc('preview_partner_invite', [tokenHash(h2)]), 'A stored hash cannot preview an invite through direct RPC');
    await assert.rejects(rpc('accept_partner_invite', [tokenHash(h2)]), 'A stored hash cannot redeem an invite through direct RPC');
    assert.equal((await rpc('partner_state')).connection, null);
    const connected = await rpc('accept_partner_invite', [h2]);
    assert.equal(connected.nickname, '민수'); assert.ok(connected.id);
    await assert.rejects(rpc('preview_partner_invite', [h2])); await assert.rejects(rpc('preview_partner_invite', [h3]));
    await assert.rejects(rpc('accept_partner_invite', [h2]));
    await assert.rejects(rpc('create_partner_invite', [h4]));
    await asUser(cara);
    await db.query("insert into partner_profiles(user_id,nickname) values($1,'수진')", [cara]);
    await rpc('create_partner_invite', [h4]);
    await asUser(alice);
    await assert.rejects(rpc('accept_partner_invite', [h4]));
    assert.equal((await rpc('partner_state')).connection.nickname, '지훈');
    const today = (await db.query("select (now() at time zone 'Asia/Seoul')::date::text as day")).rows[0].day;
    const yesterday = (await db.query("select ((now() at time zone 'Asia/Seoul')::date-1)::text as day")).rows[0].day;
    await assert.rejects(db.query("insert into daily_tasks(id,user_id,day,title,shared,shared_connection_id) values($1,$2,$3,'잘못된 상대 지정',true,$4)", [task, alice, today, hidden]));
    await db.query("insert into daily_tasks(id,user_id,day,title,shared,public_note,note,reason_detail) values($1,$2,$3,'함께 확인한 책 읽기',true,'오늘 이해한 내용','비공개 생각','')", [task, alice, today]);
    assert.equal((await db.query('select shared_connection_id from daily_tasks where id=$1', [task])).rows[0].shared_connection_id, connected.id, 'Sharing derives the actual pair');
    await db.query("insert into daily_tasks(id,user_id,day,title,status,reason,reason_detail,note) values($1,$2,$3,'숨긴 활동','partial','energy','개인 사정','숨긴 메모')", [hidden, alice, today]);
    await db.query("insert into daily_tasks(id,user_id,day,title,status,shared) values($1,$2,$3,'어제 계획하고 오늘 일부 실행','partial',true)", [partial, alice, yesterday]);
    await db.query('update daily_tasks set shared=true where id=$1', [legacy]);
    await db.query("update daily_tasks set status='completed',completed_at='2000-01-01' where id=$1", [task]);
    const completed = (await db.query('select completed_at from daily_tasks where id=$1', [task])).rows[0].completed_at;
    assert.notEqual(completed.toISOString().slice(0, 10), '2000-01-01');
    await db.query("update daily_tasks set title='수정한 책 읽기',completed_at='2000-01-01' where id=$1", [task]);
    assert.deepEqual((await db.query('select completed_at from daily_tasks where id=$1', [task])).rows[0].completed_at, completed);
    assert.equal((await db.query('select completed_at from daily_tasks where id=$1', [legacy])).rows[0].completed_at, null, 'Legacy completion never invents a timestamp');
    await db.query("insert into reading_sessions(user_id,task_id,work_title,status,finished_at,running_since,reading_day,elapsed_seconds,start_page,end_page,is_reading,memo) values($1,$2,'비공개 작품명','completed',now(),null,$3,1500,11,21,true,'비공개 집중 메모'),($1,$2,'비공개 작품명','completed',now(),null,$4,900,21,25,true,'다른 날짜 메모'),($1,$5,'할 일','completed',now(),null,$3,120,null,null,false,'비공개 학습 메모')", [alice, task, today, yesterday, partial]);
    await asUser(bob);
    assert.equal((await db.query('select * from daily_tasks')).rows.length, 0, 'A partner cannot read private base records');
    assert.equal((await db.query('select * from reading_sessions')).rows.length, 0);
    const day = await rpc('partner_day', [today]);
    assert.equal(day.nickname, '민수'); assert.equal(day.connection_id, connected.id); assert.equal(day.activities.length, 2);
    const shown = day.activities.find(item => item.id === task);
    assert.deepEqual(Object.keys(shown).sort(), ['completed_at', 'day', 'id', 'measured_seconds', 'pages', 'public_note', 'status', 'title', 'total_sessions']);
    assert.equal(shown.measured_seconds, 1500); assert.equal(shown.pages, 10); assert.equal(shown.total_sessions, 1);
    assert.equal(day.activities.find(item => item.id === partial).measured_seconds, 120);
    assert.equal(JSON.stringify(day).includes('비공개'), false);
    assert.equal((await rpc('partner_day', ['2026-10-01'])).activities[0].measured_seconds, null, 'Unmeasured is null, never invented zero');
    await asUser(alice);
    await db.query('update daily_tasks set shared=false where id=$1', [task]);
    await asUser(bob);
    assert.equal((await rpc('partner_day', [today])).activities.some(item => item.id === task), false, 'Unsharing immediately removes visibility');
    await asUser(alice);
    await db.query('update daily_tasks set shared=true where id=$1', [task]);
    await db.query("update daily_tasks set status='partial' where id=$1", [task]);
    assert.equal((await db.query('select completed_at from daily_tasks where id=$1', [task])).rows[0].completed_at, null, 'Undo clears the completion timestamp');
    await assert.rejects(rpc('revoke_partner', [hidden]));
    assert.equal((await rpc('partner_state')).connection.id, connected.id);
    await rpc('revoke_partner', [connected.id]);
    assert.equal((await rpc('partner_state')).connection, null);
    assert.equal((await db.query('select count(*)::integer as count from daily_tasks where shared')).rows[0].count, 0);
    assert.equal((await db.query('select public_note,note from daily_tasks where id=$1', [task])).rows[0].public_note, '오늘 이해한 내용');
    assert.equal((await db.query('select public_note,note from daily_tasks where id=$1', [task])).rows[0].note, '비공개 생각');
    await asUser(bob); await assert.rejects(rpc('partner_day', [today]));
    await asUser(alice); const next = await rpc('accept_partner_invite', [h4]);
    assert.notEqual(next.id, connected.id);
    await assert.rejects(rpc('revoke_partner', [connected.id]));
    assert.equal((await rpc('partner_state')).connection.id, next.id, 'A stale disconnect never revokes a different partner');
    await asUser(cara); assert.equal((await rpc('partner_day', [today])).activities.length, 0, 'New partner receives no old sharing selections');
    await asUser(alice); await db.query('update daily_tasks set shared=true where id=$1', [task]);
    const ownedWork='ffffffff-ffff-4fff-8fff-ffffffffffff';
    await db.query("insert into works(id,user_id,title,kind) values($1,$2,'삭제할 계정의 서재','book')",[ownedWork,alice]);
    await db.query("insert into notes(user_id,work_id,content) values($1,$2,'계정 삭제 시 함께 정리할 감상')",[alice,ownedWork]);
    await asUser(cara); assert.equal((await rpc('partner_day', [today])).activities.length, 1);
    const retainedTask = 'eeeeeeee-eeee-4eee-8eee-eeeeeeeeeeee';
    await db.query("insert into daily_tasks(id,user_id,day,title,shared,note,public_note) values($1,$2,$3,'남아 있는 상대의 기록',true,'나만 보는 기록','공개했던 문장')", [retainedTask, cara, today]);
    await db.exec('reset role; set role supabase_auth_admin;'); await db.query('delete from auth.users where id=$1', [alice]);
    await asUser(cara); assert.equal((await rpc('partner_state')).connection, null, 'Deleting a partner releases the remaining account');
    const retained = (await db.query('select shared,shared_connection_id,note,public_note from daily_tasks where id=$1', [retainedTask])).rows[0];
    assert.deepEqual(retained, { shared: false, shared_connection_id: null, note: '나만 보는 기록', public_note: '공개했던 문장' });
    await rpc('create_partner_invite', [h5]); await rpc('cancel_partner_invite'); await assert.rejects(rpc('preview_partner_invite', [h5]));
    await rpc('create_partner_invite', [h5]);
    await db.exec('reset role;'); await db.query("update partner_invites set expires_at=now()-interval '1 second' where user_id=$1", [cara]);
    await asUser(bob); await assert.rejects(rpc('accept_partner_invite', [h5]));
    assert.equal((await rpc('partner_state')).connection, null);
  } finally { await db.close(); }
});
